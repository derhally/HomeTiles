// Generates src/ui/assist/assist_screen_files.h: the Assist screen files
// (tools/assist-screen-lab/screens/*.json) built into firmware compiled with
// HOMETILES_ASSIST_DATA_SCREENS=1. Each file is minified and loses its "note"
// texts, which only explain the file to people.
//
// Usage: node tools/generate-assist-screens.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const screens = path.join(root, 'tools/assist-screen-lab/screens');
const target = path.join(root, 'src/ui/assist/assist_screen_files.h');

const strip = value => {
  if (Array.isArray(value)) return value.map(strip);
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).filter(([key]) => key !== 'note').map(([key, v]) => [key, strip(v)]));
  }
  return value;
};

const files = fs.readdirSync(screens).filter(f => f.endsWith('.json')).sort().map(f => {
  const json = strip(JSON.parse(fs.readFileSync(path.join(screens, f), 'utf8')));
  const text = JSON.stringify(json);
  if (text.includes(')json"')) throw new Error(`${f} contains the raw string delimiter`);
  return {id: json.id, name: `k${json.id.replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase())}`, text};
});

const lines = [
  '#pragma once',
  '',
  '// Generated by tools/generate-assist-screens.mjs from',
  '// tools/assist-screen-lab/screens/*.json; do not edit. Minified, without notes.',
  '',
  '#include <stddef.h>',
  '',
  'namespace assist_screen_files {',
  '',
  'struct File {',
  '  const char* id;',
  '  const char* text;',
  '  size_t length;',
  '};',
  '',
  ...files.map(f => `inline constexpr char ${f.name}[] = R"json(${f.text})json";`),
  '',
  'inline constexpr File kFiles[] = {',
  ...files.map(f => `    {"${f.id}", ${f.name}, sizeof(${f.name}) - 1},`),
  '};',
  'inline constexpr size_t kFileCount = sizeof(kFiles) / sizeof(kFiles[0]);',
  '',
  '}  // namespace assist_screen_files',
  '',
];
const content = lines.join('\n');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== content) {
    console.error('src/ui/assist/assist_screen_files.h is out of date: run node tools/generate-assist-screens.mjs');
    process.exit(1);
  }
  console.log('Assist screen files up to date');
} else {
  fs.writeFileSync(target, content);
  console.log(`Wrote ${path.relative(root, target)} (${files.length} screens, ${files.reduce((n, f) => n + f.text.length, 0)} bytes)`);
}
